import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { createPool } from '@certa/db';
import { createTestDatabase, type TestDatabase } from '@certa/db/testing';
import type pg from 'pg';
import { buildApp, type App } from '../src/app.js';
import { loadConfig } from '../src/config.js';
import { MemoryMailer } from '../src/lib/mailer.js';

const ORIGIN = 'http://localhost:8080';
const BOT_TOKEN = 'bot-token-bot-token-bot-token-bot-token-123';
let tdb: TestDatabase;
let pool: pg.Pool;
let app: App;

interface Session {
  cookie: string;
  orgId: string;
}

const cookieFrom = (res: { headers: Record<string, unknown> }) => {
  const raw = res.headers['set-cookie'];
  const list = Array.isArray(raw) ? raw : raw ? [raw as string] : [];
  return list.map((c: string) => c.split(';')[0]).join('; ');
};

async function signUp(name: string, email: string, org: string): Promise<Session> {
  const res = await app.inject({
    method: 'POST',
    url: '/api/v1/signup',
    headers: { origin: ORIGIN },
    payload: { name, email, password: 'correct-horse-battery', organizationName: org, timezone: 'America/Denver' },
  });
  expect(res.statusCode, res.body).toBe(201);
  return { cookie: cookieFrom(res), orgId: res.json().memberships[0].orgId };
}

const call = (s: Session, method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE', path: string, payload?: unknown) =>
  app.inject({ method, url: `/api/v1/orgs/${s.orgId}${path}`, headers: { origin: ORIGIN, cookie: s.cookie }, payload: payload as object });
const ok = async (p: ReturnType<typeof call>, status = 200) => {
  const res = await p;
  expect(res.statusCode, res.body).toBe(status);
  return res.statusCode === 204 ? null : res.json();
};

let owner: Session;
let other: Session;

beforeAll(async () => {
  tdb = await createTestDatabase('discord');
  pool = createPool(tdb.appUrl);
  const config = loadConfig({
    NODE_ENV: 'test',
    DATABASE_URL: tdb.appUrl,
    AUTH_SECRET: 'test-secret-test-secret-test-secret-123',
    PUBLIC_URL: ORIGIN,
    LOG_LEVEL: 'error',
    RATE_LIMIT_AUTH_PER_MINUTE: '1000',
    DISCORD_BOT_API_TOKEN: BOT_TOKEN,
  });
  app = await buildApp({ config, pool, mailer: new MemoryMailer() });
  owner = await signUp('Olivia Owner', 'olivia@example.com', 'Skyline Aerial');
  other = await signUp('Oscar Other', 'oscar@example.com', 'Other Co');
});

afterAll(async () => {
  await app?.close();
  await pool?.end();
  await tdb?.drop();
});


const bot = (method: 'GET' | 'POST', path: string, payload?: unknown, headers: Record<string, string> = {}, token = BOT_TOKEN) =>
  app.inject({ method, url: `/api/v1${path}`, headers: { authorization: `Bearer ${token}`, ...headers }, payload: payload as object });
const botOk = async (p: ReturnType<typeof bot>, status = 200) => {
  const res = await p;
  expect(res.statusCode, res.body).toBe(status);
  return res.json();
};
const DISCORD_A = '123456789012345678';
const DISCORD_B = '223456789012345678';

describe('Discord link for the community bot', () => {
  let certaUserId: string;
  const flight = { date: new Date(Date.now() - 86400_000).toLocaleDateString('en-CA', { timeZone: 'America/Denver' }), location: 'kapa', locationIsIcao: true, aircraft: 'falcon 1', durationMinutes: 25, missionType: 'Inspection' };

  it('rejects the bot without the right token', async () => {
    expect((await bot('GET', '/leaderboard', undefined, {}, 'wrong-token')).statusCode).toBe(401);
    expect((await app.inject({ method: 'GET', url: '/api/v1/leaderboard' })).statusCode).toBe(401);
  });

  it('links with a single-use code generated by the pilot', async () => {
    const before = await ok(call(owner, 'GET', '/discord/link'));
    expect(before).toMatchObject({ canLink: true, linked: false, leaderboardOptIn: false, orgLeaderboardEnabled: true, canManageOrg: true });
    const first = await ok(call(owner, 'POST', '/discord/link-code'), 201);
    const { code } = await ok(call(owner, 'POST', '/discord/link-code'), 201);
    expect(code).toMatch(/^CERTA-[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}$/);
    // Issuing a new code cancels the previous one.
    await botOk(bot('POST', '/discord/link-codes/redeem', { code: first.code, discordUserId: DISCORD_A }), 404);
    const linked = await botOk(bot('POST', '/discord/link-codes/redeem', { code: ` ${code.toLowerCase()} `, discordUserId: DISCORD_A }));
    expect(linked.displayName).toBe('Olivia Owner');
    certaUserId = linked.certaUserId;
    // Single use.
    const again = await bot('POST', '/discord/link-codes/redeem', { code, discordUserId: DISCORD_B });
    expect(again.statusCode).toBe(404);
    expect(again.json().message).toMatch(/expired or already been used/);
    expect(await ok(call(owner, 'GET', '/discord/link'))).toMatchObject({ linked: true });
  });

  it('logs flights from Discord against a real aircraft, idempotently', async () => {
    const miss = await bot('POST', `/users/${certaUserId}/flights`, flight, { 'idempotency-key': 'k1' });
    expect(miss.statusCode).toBe(422);
    expect(miss.json().message).toMatch(/No aircraft called/);
    await ok(call(owner, 'POST', '/aircraft', { nickname: 'Falcon 1', make: 'DJI', model: 'Mavic 3 Enterprise', serialNumber: 'DJI-1' }), 201);
    await ok(call(owner, 'POST', '/aircraft', { nickname: 'Falcon 2', make: 'DJI', model: 'Mavic 3 Enterprise', serialNumber: 'DJI-2' }), 201);
    const ambiguous = await bot('POST', `/users/${certaUserId}/flights`, { ...flight, aircraft: 'DJI Mavic 3 Enterprise' }, { 'idempotency-key': 'k0' });
    expect(ambiguous.statusCode).toBe(422);
    expect(ambiguous.json().message).toMatch(/matches 2 aircraft/);
    await botOk(bot('POST', `/users/${certaUserId}/flights`, { ...flight, date: '2999-01-01' }, { 'idempotency-key': 'kf' }), 422);

    const made = await botOk(bot('POST', `/users/${certaUserId}/flights`, flight, { 'idempotency-key': 'k1' }), 201);
    const retry = await botOk(bot('POST', `/users/${certaUserId}/flights`, flight, { 'idempotency-key': 'k1' }), 200);
    expect(retry.flightId).toBe(made.flightId);
    const f = await ok(call(owner, 'GET', `/flights/${made.flightId}`));
    expect(f).toMatchObject({ locationName: 'KAPA', durationSeconds: 1500, operationType: 'commercial', localTimeZone: 'America/Denver' });
    expect(new Date(f.takeoffAt).toLocaleTimeString('en-US', { timeZone: 'America/Denver', hour12: false })).toBe('12:00:00');
    expect(f.notes).toMatch(/takeoff time not recorded/);

    const totals = await botOk(bot('GET', `/users/${certaUserId}/flight-totals`));
    expect(totals).toMatchObject({ totalFlights: 1, totalMinutes: 25, last30Days: { flights: 1, minutes: 25 } });
  });

  it('reports Part 107 currency with the rule pack due date', async () => {
    expect(await botOk(bot('GET', `/users/${certaUserId}/currency`))).toMatchObject({ lastTrainingDate: null, lastTrainingKind: null });
    const pilotId = (await ok(call(owner, 'GET', '/fleet'))).pilots.find((p: { displayName: string }) => p.displayName === 'Olivia Owner').id;
    await ok(call(owner, 'POST', `/pilots/${pilotId}/credentials`, { credentialType: 'part107_certificate', issuedOn: '2024-03-01' }), 201);
    await ok(call(owner, 'POST', `/pilots/${pilotId}/credentials`, { credentialType: 'part107_recurrent', issuedOn: '2025-11-02' }), 201);
    const c = await botOk(bot('GET', `/users/${certaUserId}/currency`));
    expect(c).toMatchObject({ lastTrainingDate: '2025-11-02', lastTrainingKind: 'recurrent', dueDate: expect.stringMatching(/^2027-11/) });
    expect(['current', 'due_soon']).toContain(c.status);
  });

  it('shows the leaderboard only to pilots who opt in, in orgs that allow it', async () => {
    expect((await botOk(bot('GET', '/leaderboard?period=all'))).entries).toEqual([]);
    expect(await ok(call(owner, 'PATCH', '/discord/link', { leaderboardOptIn: true }))).toMatchObject({ leaderboardOptIn: true });
    const all = (await botOk(bot('GET', '/leaderboard?period=all'))).entries;
    expect(all).toEqual([{ rank: 1, certaUserId, displayName: 'Olivia Owner', totalMinutes: 25, flightCount: 1 }]);
    expect((await botOk(bot('GET', '/leaderboard?period=month&month=2001-01'))).entries).toEqual([]);
    await ok(call(owner, 'PUT', '/discord/settings', { leaderboardEnabled: false }));
    expect((await botOk(bot('GET', '/leaderboard?period=all'))).entries).toEqual([]);
    await ok(call(owner, 'PUT', '/discord/settings', { leaderboardEnabled: true }));
  });

  it('keeps orgs apart, moves a Discord account between pilots, and cuts access on unlink', async () => {
    // Another org's pilot links the same Discord account: the first link ends.
    const { code } = await ok(call(other, 'POST', '/discord/link-code'), 201);
    const otherLink = await botOk(bot('POST', '/discord/link-codes/redeem', { code, discordUserId: DISCORD_A }));
    expect(otherLink.certaUserId).not.toBe(certaUserId);
    await botOk(bot('GET', `/users/${certaUserId}/flight-totals`), 404);
    expect(await ok(call(owner, 'GET', '/discord/link'))).toMatchObject({ linked: false });
    // The other org sees only its own pilot's data through its link.
    expect(await botOk(bot('GET', `/users/${otherLink.certaUserId}/flight-totals`))).toMatchObject({ totalFlights: 0 });
    // Members of another org can't change this org's leaderboard setting.
    await ok(call(other, 'GET', '/discord/link'));
    await ok(call(other, 'DELETE', '/discord/link'), 204);
    await botOk(bot('GET', `/users/${otherLink.certaUserId}/currency`), 404);
    await botOk(bot('POST', `/users/${otherLink.certaUserId}/flights`, flight), 404);
  });
});
