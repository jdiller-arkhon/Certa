/**
 * Inspector packet: a one-page, read-only summary of one pilot's or one aircraft's compliance
 * records, for an FAA inspector, client, or insurer. The API serves it as JSON (behind a
 * time-boxed share link) and as a sealed PDF; the web viewer renders the same object.
 *
 * Pure: built from the fleet snapshot plus recent flights. The API seals it (SHA-256 of the
 * canonical JSON) so a printed or forwarded copy can be checked against the live record.
 */
import { z } from 'zod';
import type { Flight } from '../domain/entities.js';
import { addDays } from '../format/dates.js';
import { formatDuration, formatMass } from '../format/units.js';
import { evaluateItem, DEFAULT_READINESS_POLICY } from '../readiness/readiness.js';
import { credentialExpiry } from '../rules/evaluators.js';
import { REMOTE_ID_LABEL } from '../viewmodels/builders.js';
import { aircraftName, type MapContext } from '../viewmodels/mappers.js';
import { fleetReadiness, fullAircraftItems, type FleetSnapshot } from './fleet.js';

const Level = z.enum(['green', 'amber', 'red']);

export const InspectorPacket = z.object({
  version: z.literal(1),
  organization: z.string(),
  generatedAt: z.string(),
  asOf: z.string(),
  ruleSet: z.string(),
  subject: z.object({
    type: z.enum(['pilot', 'aircraft']),
    name: z.string(),
    facts: z.array(z.tuple([z.string(), z.string()])),
  }),
  status: z.object({ level: Level, label: z.string() }),
  records: z.array(z.object({ label: z.string(), level: Level, status: z.string(), due: z.string().nullable(), detail: z.string() })),
  activity: z.object({
    flights: z.number().int(),
    flightTime: z.string(),
    last90Flights: z.number().int(),
    last90FlightTime: z.string(),
  }),
  recentFlights: z.array(
    z.object({
      date: z.string(),
      duration: z.string(),
      with: z.string(),
      location: z.string().nullable(),
      /** Pre-flight checklist signed with the flight. Absent in packets sealed before checklists existed. */
      checklist: z.enum(['complete', 'incomplete', 'none']).optional(),
    }),
  ),
  disclaimer: z.string(),
});
export type InspectorPacket = z.infer<typeof InspectorPacket>;

const STATUS = { green: 'Current', amber: 'Attention', red: 'Not current' } as const;
const SUBJECT_STATUS = {
  pilot: { green: 'Current — legal to fly', amber: 'Current — attention needed soon', red: 'Not current' },
  aircraft: { green: 'Airworthy on record', amber: 'Airworthy — attention needed soon', red: 'Not airworthy on record' },
} as const;

export const PACKET_DISCLAIMER =
  'Generated by Certa from records entered by the operator. Certa is a record-keeping tool; the operator remains responsible for compliance. Regulatory values are pending verification by a qualified person.';

function recordStatus(level: 'green' | 'amber' | 'red', days: number | null, blocking: boolean) {
  if (blocking) return 'Not current';
  if (days == null) return STATUS[level];
  if (days < 0) return `Expired ${-days} days ago`;
  if (level === 'amber') return `Expires in ${days} days`;
  return 'Current';
}

export function buildInspectorPacket(
  s: FleetSnapshot,
  subject: { type: 'pilot' | 'aircraft'; id: string },
  flights: Flight[],
  ctx: MapContext,
  /** Flight id → whether its pre-flight checklist was completed; flights without a run are absent. */
  checklists: Map<string, boolean> = new Map(),
): InspectorPacket | null {
  const r = fleetReadiness(s, ctx);
  const policy = ctx.policy ?? DEFAULT_READINESS_POLICY;
  const pilotNames = new Map(s.pilots.map((p) => [p.id, p.displayName]));
  const acNames = new Map(s.aircraft.map((a) => [a.id, aircraftName(a)]));
  const since90 = `${addDays(ctx.today, -90)}T00:00:00Z`;
  const mine = flights.filter((f) => !f.deletedAt && (subject.type === 'pilot' ? f.pilotInCommandId === subject.id : f.aircraftId === subject.id));
  const recent90 = mine.filter((f) => f.takeoffAt >= since90);
  const sum = (fs: Flight[]) => fs.reduce((t, f) => t + f.durationSeconds, 0);

  let name: string;
  let facts: [string, string][];
  let records: InspectorPacket['records'];
  let level: 'green' | 'amber' | 'red';
  let totals: { flights: number; seconds: number };

  if (subject.type === 'pilot') {
    const p = s.pilots.find((x) => x.id === subject.id && !x.deletedAt);
    const summary = p && r.pilots.get(p.id);
    if (!p || !summary) return null;
    name = p.displayName;
    facts = [['Remote pilot certificate', p.certificateNumber ?? 'Not on file']];
    const creds = s.credentials.filter((c) => c.pilotId === p.id && !c.deletedAt);
    records = summary.items.map((it) => {
      const cred = creds.find((c) => it.key === `credential:${c.id}`);
      const exp = cred ? credentialExpiry(cred, r.rules) : null;
      const detail = cred
        ? [cred.identifier && `No. ${cred.identifier}`, cred.issuedOn && `issued ${cred.issuedOn}`, exp?.basis === 'non_expiring' ? 'does not expire' : null].filter(Boolean).join(' · ')
        : 'Not on file';
      return { label: it.label.replace(/ not on file$/, ''), level: it.level, status: recordStatus(it.level, it.daysRemaining, it.blocking || it.kind === 'credential_missing'), due: it.dueOn, detail };
    });
    level = summary.level;
    const t = s.pilotTotals[p.id];
    totals = { flights: t?.flights ?? mine.length, seconds: t?.flightSeconds ?? sum(mine) };
  } else {
    const a = s.aircraft.find((x) => x.id === subject.id && !x.deletedAt);
    if (!a) return null;
    const summary = r.aircraft.get(a.id);
    name = aircraftName(a);
    facts = [
      ['Make / model', `${a.make} ${a.model}`],
      ['Serial number', a.serialNumber],
      ['Registration', a.registrationNumber ?? 'Not on file'],
      ['Remote ID', `${REMOTE_ID_LABEL[a.remoteIdMethod] ?? a.remoteIdMethod}${a.remoteIdSerial ? ` · ${a.remoteIdSerial}` : ''}`],
      ...(a.takeoffMassKg != null ? [['Takeoff mass', formatMass(a.takeoffMassKg, ctx.units).display] as [string, string]] : []),
      ...(a.status === 'retired' ? [['Status', 'Retired'] as [string, string]] : []),
    ];
    const items = summary?.items ?? fullAircraftItems(a, s, r.rules).map((i) => evaluateItem(i, ctx.today, policy));
    records = items.map((it) => ({
      label: it.label,
      level: it.level,
      status: it.usageFraction != null && it.usageFraction >= 1 ? 'Overdue' : recordStatus(it.level, it.daysRemaining, it.blocking),
      due: it.dueOn,
      detail: it.usageFraction != null ? `${Math.round(it.usageFraction * 100)}% of interval used` : '',
    }));
    level = a.status === 'retired' ? 'red' : (summary?.level ?? 'green');
    totals = { flights: a.totalFlights, seconds: a.totalFlightSeconds };
  }

  return {
    version: 1,
    organization: s.organization.name,
    generatedAt: ctx.now.toISOString(),
    asOf: ctx.today,
    ruleSet: `${s.rulePack.name} v${s.rulePack.version}`,
    subject: { type: subject.type, name, facts },
    status: { level, label: SUBJECT_STATUS[subject.type][level] },
    records,
    activity: {
      flights: totals.flights,
      flightTime: formatDuration(totals.seconds).display,
      last90Flights: recent90.length,
      last90FlightTime: formatDuration(sum(recent90)).display,
    },
    recentFlights: mine.slice(0, 15).map((f) => ({
      date: f.takeoffAt.slice(0, 10),
      duration: formatDuration(f.durationSeconds).display,
      with: subject.type === 'pilot' ? (acNames.get(f.aircraftId) ?? 'Aircraft') : (pilotNames.get(f.pilotInCommandId) ?? 'Pilot'),
      location: f.locationName,
      checklist: checklists.has(f.id) ? (checklists.get(f.id) ? 'complete' : 'incomplete') : 'none',
    })),
    disclaimer: PACKET_DISCLAIMER,
  };
}
